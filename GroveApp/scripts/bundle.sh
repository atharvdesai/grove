#!/usr/bin/env bash
#
# Wraps the SwiftPM executable into Grove.app.
#
# A bundle is not cosmetic here. macOS needs one for the menu-bar item and the
# app lifecycle, and TCC reads the microphone and audio-capture usage strings
# from Contents/Info.plist — a bare executable gets a permission dialog with no
# explanation, or none at all.
#
#   ./scripts/bundle.sh            # debug
#   ./scripts/bundle.sh release
#   ./scripts/bundle.sh release --run
set -euo pipefail

cd "$(dirname "$0")/.."

CONFIGURATION="debug"
RUN=false
for argument in "$@"; do
    case "$argument" in
        debug|release) CONFIGURATION="$argument" ;;
        --run) RUN=true ;;
        *) echo "usage: bundle.sh [debug|release] [--run]" >&2; exit 2 ;;
    esac
done

# Extra flags for `swift build`, mainly so packagers can pass --disable-sandbox.
# SwiftPM sandboxes its own manifest evaluation, and that cannot nest inside an
# outer sandbox: under `brew install` it fails with
#   sandbox-exec: sandbox_apply: Operation not permitted
# which reads like a permissions problem with the formula rather than what it
# is. Word splitting is intended here.
# shellcheck disable=SC2086
SWIFT_BUILD_FLAGS="${SWIFT_BUILD_FLAGS:-}"

swift build -c "$CONFIGURATION" $SWIFT_BUILD_FLAGS
BINARY="$(swift build -c "$CONFIGURATION" $SWIFT_BUILD_FLAGS --show-bin-path)/GroveApp"

APP="build/Grove.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# CFBundleExecutable is "Grove", so the binary is renamed rather than symlinked.
cp "$BINARY" "$APP/Contents/MacOS/Grove"
cp Resources/Info.plist "$APP/Contents/Info.plist"

# Google sign-in needs an OAuth client ID (an "iOS" type client from Google
# Cloud Console). It is kept out of the repo: put it in google-client-id.txt
# next to this package, or export GROVE_GOOGLE_CLIENT_ID. Without one the app
# still builds and works; the Google features just say they aren't set up.
GOOGLE_CLIENT_ID="${GROVE_GOOGLE_CLIENT_ID:-}"
if [ -z "$GOOGLE_CLIENT_ID" ] && [ -f google-client-id.txt ]; then
    GOOGLE_CLIENT_ID="$(tr -d '[:space:]' < google-client-id.txt)"
fi
if [ -n "$GOOGLE_CLIENT_ID" ]; then
    plutil -replace GroveGoogleClientID -string "$GOOGLE_CLIENT_ID" "$APP/Contents/Info.plist"
fi

# Generated by ../scripts/make-icon.py. Missing it is not fatal — the app still
# runs, just with the generic blank icon — so warn rather than fail a build.
if [ -f Resources/Grove.icns ]; then
    cp Resources/Grove.icns "$APP/Contents/Resources/Grove.icns"
else
    echo "warning: Resources/Grove.icns is missing; run ../scripts/make-icon.py"
fi
printf 'APPL????' > "$APP/Contents/PkgInfo"

# Extended attributes must go before signing. Files copied around a Mac pick up
# things like com.apple.provenance and quarantine flags, and codesign refuses
# the whole bundle with "resource fork, Finder information, or similar detritus
# not allowed" — which names the symptom and not the cause.
xattr -cr "$APP"

# Ad-hoc signature. There is no Developer ID on this machine yet, and an
# unsigned bundle is treated with more suspicion by TCC than an ad-hoc one.
#
# Caveat worth knowing before you debug a permission that "randomly" reset:
# ad-hoc signing means the code identity changes on every rebuild, so macOS can
# treat each build as a new app and ask for microphone access again. That is a
# property of unsigned development builds, not a bug in Grove.
codesign --force --sign - --identifier app.grove.Grove "$APP" >/dev/null 2>&1 \
    || echo "warning: ad-hoc codesign failed; the app will still run but TCC may re-prompt"

echo "built $APP ($CONFIGURATION)"

if [ "$RUN" = true ]; then
    # `open` so it launches as a real bundled app with a menu bar, rather than
    # as a child of this shell.
    open "$APP"
fi
